const FIELDS = ["on", "label", "img", "cta", "title", "desc", "h1", "text"];

// Defaults + the owner's saved changes
export async function loadSeo(env) {
  let saved = null;
  try { if (env && env.ORDERS) saved = await env.ORDERS.get("seo", "json"); } catch (e) {}
  return mergeSeo(saved);
}
export function mergeSeo(saved) {
  const d = DEFAULTS, s = saved || {};
  const out = { keywords: Array.isArray(s.keywords) ? s.keywords : d.keywords.slice(), home: Object.fromEntries(Object.keys(d.home).map(f => [f, (s.home || {})[f] || d.home[f]])), pages: {} };
  for (const k of Object.keys(d.pages)) {
    const p = { ...d.pages[k] }, sp = (s.pages || {})[k] || {};
    for (const f of FIELDS) if (sp[f] !== undefined && sp[f] !== "") p[f] = sp[f];
    out.pages[k] = p;
  }
  return out;
}
// Keep only known fields and sane sizes when saving
export function cleanSeo(x) {
  const str = (v, n) => String(v ?? "").slice(0, n);
  const out = { keywords: (Array.isArray(x.keywords) ? x.keywords : []).map(k => str(k, 80).trim()).filter(Boolean).slice(0, 200), home: {}, pages: {} };
  const h = x.home || {};
  out.home = { title: str(h.title, 120), desc: str(h.desc, 300), text: str(h.text, 2000) };
  for (const k of Object.keys(DEFAULTS.pages)) {
    const p = (x.pages || {})[k]; if (!p) continue;
    out.pages[k] = { on: !!p.on, title: str(p.title, 120), desc: str(p.desc, 300), h1: str(p.h1, 120), text: str(p.text, 8000) };
  }
  return out;
}

export const esc = s => String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));

// Simple text format: blank line = new paragraph, "## " = heading, "- " = list item, "> " = quote
export function textToHtml(t) {
  const out = []; let list = null;
  const flush = () => { if (list) { out.push("<ul>" + list.join("") + "</ul>"); list = null; } };
  for (const block of String(t || "").split(/\n\s*\n/)) {
    for (const raw of block.split("\n")) {
      const l = raw.trim(); if (!l) continue;
      if (l.startsWith("- ")) { (list = list || []).push("<li>" + esc(l.slice(2)) + "</li>"); continue; }
      flush();
      if (l.startsWith("## ")) out.push("<h2>" + esc(l.slice(3)) + "</h2>");
      else if (l.startsWith("> ")) out.push("<blockquote>" + esc(l.slice(2)) + "</blockquote>");
      else out.push("<p>" + esc(l) + "</p>");
    }
    flush();
  }
  return out.join("\n");
}

